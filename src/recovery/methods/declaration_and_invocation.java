package recovery.methods;
/*
адача «Калькулятор прямоугольника»

Создай два метода:
- calculateArea(int width, int height) — принимает ширину и высоту, возвращает площадь прямоугольника.
- printArea(int area) — принимает площадь и выводит её в консоль.
*/
public class declaration_and_invocation {
    public int calculateArea(int width, int height) {
        return width * height;
    }

    public void printArea(int area) {
        System.out.println(area);
    }
}
